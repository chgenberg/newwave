const VARSITY = /varsity|college|graduate|athletic|freshman/i;
const CONDENSED = /condensed|compressed|narrow|anton|oswald|bebas|league gothic|impact/i;
const SANS = /sans|arial|helvetica|futura|gotham|montserrat|roboto|\binter\b|verdana|avenir|proxima|franklin|gill|\bdin\b|myriad|segoe|lato|poppins|nunito|univers|frutiger|akzidenz|grotes|tahoma|trebuchet|archivo/i;
/** Franklin Gothic och Century Gothic är sans – Fraktur känns igen på sina egna namn. */
const GOTHIC = /fraktur|blackletter|old english|textura|cloister|pirata/i;
const SERIF = /serif|playfair|cinzel|garamond|didot|bodoni|times|trajan|georgia|minion|caslon|baskerville|palatino|cambria|merriweather/i;

/** Gissar rollen ur ett typsnittsnamn från en Illustrator-fil, så att importen kan välja ett licensierat typsnitt i samma stil. */
export function roleFromFamily(family: string): FontRole {
  if (GOTHIC.test(family)) return "gothic";
  if (SCRIPT.test(family)) return "script";
  if (VARSITY.test(family)) return "varsity";
  if (SLAB.test(family)) return "caps";
  if (CONDENSED.test(family)) return "condensed";
  if (SANS.test(family)) return "block";
  if (SERIF.test(family)) return "serif";
  return "caps";
}
