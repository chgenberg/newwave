export const DICT: Record<Lang, Dict> = { de: DE, sv: SV };
export type ShopDict = Dict;

const list = (words: string[], and: string) => (words.length > 1 ? `${words.slice(0, -1).join(", ")} ${and} ${words.at(-1)}` : (words[0] ?? ""));
export const sportsOf = (c: ShopClub, lang: Lang) => list(c.sports.map((s) => DICT[lang].sports[s]), lang === "de" ? "und" : "och");
export const productName = (kind: Kind, club: ShopClub, lang: Lang) => `${DICT[lang].kinds[kind]} ${club.short}`;

const fold = (s: string) => s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
/** Alla sökord finns i produktnamnet eller klubbens namn, oavsett versaler och accenter. */
export function matchesQuery(p: ShopProduct, q: string, lang: Lang) {
  const club = shopClub(p.clubId);
  if (!club) return false;
  const text = fold(`${productName(p.kind, club, lang)} ${club.name}`);
  return fold(q).split(/\s+/).filter(Boolean).every((w) => text.includes(w));
}
